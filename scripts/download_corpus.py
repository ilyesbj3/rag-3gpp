"""Download the pinned 3GPP spec archives into data/raw/ and write data/VERSIONS.md.

Usage:
    python scripts/download_corpus.py [--force]

Each archive is checked to be a valid zip containing at least one .docx (or .doc).
If the download fails (no network, proxy, 3gpp.org blocking), place the zips manually in
data/raw/ under the names from config.yaml and re-run: existing files are verified, not
re-downloaded.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import urllib.request
import zipfile
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import DATA_DIR, RAW_DIR, SpecConfig, load_settings  # noqa: E402

USER_AGENT = "Mozilla/5.0 (compatible; rag-3gpp-corpus-downloader/0.1)"


def download(url: str, dest: Path, timeout: float = 120.0) -> None:
    """Stream `url` to `dest` (via a .part file so an interrupted download is not kept)."""
    tmp = dest.with_suffix(dest.suffix + ".part")
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=timeout) as resp, tmp.open("wb") as fh:
        while block := resp.read(1 << 16):
            fh.write(block)
    tmp.replace(dest)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def inspect_zip(path: Path) -> list[str]:
    """Return the Word documents inside the archive; raise if the zip is invalid."""
    with zipfile.ZipFile(path) as zf:
        bad = zf.testzip()
        if bad is not None:
            raise zipfile.BadZipFile(f"corrupt member {bad}")
        docs = [n for n in zf.namelist() if n.lower().endswith((".docx", ".doc"))]
    if not docs:
        raise ValueError(f"{path.name} contains no .docx/.doc file")
    return sorted(docs)


def fetch_spec(spec: SpecConfig, force: bool) -> dict[str, str]:
    dest = RAW_DIR / spec.file
    if force or not dest.exists():
        print(f"Downloading {spec.id} {spec.version} from {spec.url} ...")
        download(spec.url, dest)
        source = "downloaded"
    else:
        print(f"{dest.name} already present, verifying ...")
        source = "existing file"
    docs = inspect_zip(dest)
    return {
        "spec": spec.id,
        "version": spec.version,
        "release": spec.release,
        "file": spec.file,
        "url": spec.url,
        "date": datetime.fromtimestamp(dest.stat().st_mtime, UTC).strftime("%Y-%m-%d"),
        "sha256": sha256(dest),
        "size": f"{dest.stat().st_size:,} B",
        "docs": ", ".join(docs),
        "source": source,
    }


def write_versions(rows: list[dict[str, str]]) -> Path:
    out = DATA_DIR / "VERSIONS.md"
    lines = [
        "# Corpus provenance",
        "",
        "Pinned 3GPP specifications used by this project (see `config.yaml`).",
        "Generated by `scripts/download_corpus.py`; do not edit by hand.",
        "",
        "| Spec | Version | Release | File | Download date (UTC) | Size | Word documents inside |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['spec']} | {r['version']} | {r['release']} | `{r['file']}` | {r['date']} "
            f"| {r['size']} | {r['docs']} |"
        )
    lines += ["", "## Sources and checksums", ""]
    for r in rows:
        lines += [f"- **{r['spec']}** — <{r['url']}>", f"  - SHA-256: `{r['sha256']}`"]
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true", help="re-download even if present")
    args = ap.parse_args()

    RAW_DIR.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, str]] = []
    for spec in load_settings().corpus.specs:
        try:
            rows.append(fetch_spec(spec, args.force))
        except Exception as e:  # network, proxy, corrupt archive
            print(
                f"\nERROR for {spec.id}: {e!r}\n"
                f"Download {spec.url} manually and save it as {RAW_DIR / spec.file}, "
                "then re-run this script.",
                file=sys.stderr,
            )
            return 1
        r = rows[-1]
        print(f"  ok: {r['size']}, sha256={r['sha256'][:16]}..., docs: {r['docs']}")
    print(f"Wrote {write_versions(rows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
